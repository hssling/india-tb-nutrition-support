class Table(NamedTuple):
    label: str            # "Table 1", "Table S3"
    title: str
    header: list[str]
    rows: list[list[str]]  # a spanning block label is ["**label**", "", ...]
    notes: list[str]

    @property
    def csv_name(self) -> str:
        """Table 1 -> table1.csv; Table S3 -> tables3.csv."""
        return "table" + self.label.split()[1].lower() + ".csv"


def block(label: str, ncol: int) -> list[str]:
    return [f"**{label}**"] + [""] * (ncol - 1)


def chain(root: Path) -> list[dict]:
    return read_csv(root, "outputs/chain.csv")


def headline(root: Path) -> dict[str, dict]:
    return {r["hypothesis"]: r for r in read_csv(root, "outputs/headline.csv")}


def priority(root: Path, spec: str, year: str = MAIN_YEAR) -> dict[str, dict]:
    return {r["unit"]: r for r in read_csv(root, "outputs/priority.csv") if r["year"] == year and r["spec"] == spec}


def act_now(root: Path, spec: str) -> list[str]:
    return sorted(u for u, r in priority(root, spec).items() if r["tier"] == "act now")


def classes(root: Path, spec: str = "p75") -> dict[str, dict]:
    return {r["unit"]: r for r in read_csv(root, "outputs/chain_class.csv") if r["year"] == MAIN_YEAR and r["spec"] == spec}


def class_counts(root: Path) -> dict[str, int]:
    cl = [r["class"] for r in classes(root).values() if r["class"]]
    return {k: cl.count(k) for k in ("payment-led", "account-led", "mixed", "no shortfall")}


def h_value(h: dict) -> str:
    return ratio_ci(h["estimate"], h["lo"], h["hi"])


def label_cell(h: dict) -> str:
    return f"{h['label']} ({count(h['n_agree'])} of {count(h['n_entries'])} grid entries agree in sign)"


def spec_entry(root: Path, hyp: str, entry: str) -> dict:
    return one(read_csv(root, "outputs/spec_curve.csv"), f"{hyp} entry {entry}", hypothesis=hyp, entry=entry)


def budget(root: Path) -> list[dict]:
    return read_csv(root, "outputs/budget.csv")


def share(x: str, lo: str = "", hi: str = "") -> str:
    """A share with its interval, or the dash when NA."""
    if not x:
        return DASH
    return share_ci(x, lo, hi) if lo else pct(x)


def cnt(x: str) -> str:
    return count(x) if x not in ("", "NA") else DASH


