def pages(rows: list[dict]) -> str:
    ps = sorted({int(x) for r in rows for x in r["pdf_page"].split(";")})
    return f"p. {ps[0]}" if len(ps) == 1 else f"pp. {ps[0]}–{ps[-1]}"


def report(rows: list[dict]) -> str:
    names = sorted({REPORT[Path(r["source_file"]).name] for r in rows})
    return "; ".join(names)


def total_check(root: Path, key: str) -> str:
    rs = [r for r in read_csv(root, "data/extracted/total_checks.csv") if r["table_key"] == key]
    ok = sum(r["difference"] == "0" for r in rs)
    blank = sum(int(r["blank_cells"]) for r in rs)
    return (f"State rows sum to the printed India row in {count(ok)} of {count(len(rs))} columns"
            + (f" ({count(blank)} blank or dash cell{'s' if blank != 1 else ''} counted as 0)" if blank else ""))


