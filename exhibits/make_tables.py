def validated_split(root: Path) -> dict:
    """The national 2023 chain with its validated step: sums over the units with data of eligible (D),
    bank details available (B), validated (Vd) and paid at least once (Q); V = Vd/B and PV = Q/Vd."""
    us = [r for r in unit_rows(chain(root), MAIN_YEAR) if r["C"]]
    D, B, Vd, Q = (sum(int(r[k]) for r in us) for k in ("D_denominator", "B_bank_available", "bank_validated",
                                                         "Q_paid_at_least_once"))
    return {"units": len(us), "D": D, "B": B, "Vd": Vd, "Q": Q, "V": Vd / B, "PV": Q / Vd}


CLASS_ORDER = ["account-led", "payment-led", "mixed", "no shortfall"]


def class_people(root: Path, omit: tuple[str, ...] = ()) -> dict[str, dict]:
    """By 2023 class (75th-percentile benchmark): units, people not paid at least once (U, U_acc, U_pay)
    and the benchmark shortfalls S_acc and S_pay summed over the units of the class; "all" holds the
    totals. Units in `omit` are left out (for the without-Punjab rows)."""
    sf = {r["unit"]: r for r in read_csv(root, "outputs/shortfall.csv")
          if r["year"] == MAIN_YEAR and r["spec"] == "p75" and r["class"] and r["unit"] not in omit}
    ch = {r["unit"]: r for r in unit_rows(chain(root), MAIN_YEAR)}
    out: dict[str, dict] = {}
    for k in CLASS_ORDER + ["all"]:
        us = [u for u, r in sf.items() if k in ("all", r["class"])]
        out[k] = {"units": len(us), "U": sum(int(ch[u]["U"]) for u in us),
                  "U_acc": sum(int(ch[u]["U_acc"]) for u in us), "U_pay": sum(int(ch[u]["U_pay"]) for u in us),
                  "S_acc": sum(float(sf[u]["S_acc"]) for u in us), "S_pay": sum(float(sf[u]["S_pay"]) for u in us),
                  "names": sorted(us)}
    return out


def tables_classes(root: Path) -> Table:
    rows = []
    for omit, lab in (((), "All units with data"), (("Punjab",), "Without Punjab")):
        cp = class_people(root, omit)
        rows.append([f"**{lab}**", "", "", "", "", "", ""])
        for k in CLASS_ORDER + ["all"]:
            c = cp[k]
            rows.append([k if k != "all" else "Total", count(c["units"]), count(c["U"]), count(c["U_acc"]),
                         count(c["U_pay"]), count(c["S_acc"]), count(c["S_pay"])])
    notes = ["Data year 2023, the 75th-percentile benchmark, units with data (Karnataka has no 2023 denominator). People "
             "not paid at least once are the printed counts: U_acc = eligible − bank details available, U_pay = bank "
             "details available − paid at least once. S_acc and S_pay are the observed shortfalls against the benchmark "
             "(people). Sums computed from the study outputs by the exhibit code; they are descriptive and carry no "
             "interval. Punjab's 2023 row is reported as printed (a probable reporting anomaly)."]
    return Table("S:classes", "People not paid at least once and benchmark shortfalls by class, 2023, with and without "
                 "Punjab", ["Class", "Units", "Not paid at least once (U)", "Lost before bank details (U_acc)",
                            "Lost after bank details (U_pay)", "Account shortfall S_acc", "Payment shortfall S_pay"],
                 rows, notes)


