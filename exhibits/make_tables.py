def md_cell(s: str) -> str:
    if "|" in s:
        raise ValueError(f"a cell holds '|': {s!r}")
    return s


def render_md(tables: list[Table]) -> str:
    """tables.md: the variable names written as Pandoc subscripts (U~acc~), the header line aside."""
    return HEADER + "\n" + subscripts(_render_md(tables).split("\n", 1)[1])


def _render_md(tables: list[Table]) -> str:
    out = [HEADER, ""]
    for t in tables:
        out += [f"## {t.label}. {t.title}", ""]
        out.append("| " + " | ".join(t.header) + " |")
        out.append("|" + "|".join("---" for _ in t.header) + "|")
        for r in t.rows:
            if len(r) != len(t.header):
                raise ValueError(f"{t.label}: a row has {len(r)} cells, the header {len(t.header)}")
            out.append("| " + " | ".join(md_cell(c) for c in r) + " |")
        out.append("")
        for n in t.notes:
            out += [n, ""]
    return "\n".join(out).rstrip("\n") + "\n"


def plain(c: str) -> str:
    """A cell without Markdown: bold and italic markers removed, subscripts written with "_"."""
    c = re.sub(r"~(\w+)~", r"_\1", c)
    return c.replace("**", "").replace("*", "")


def csv_bytes(t: Table) -> bytes:
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow([plain(h) for h in t.header])
    for r in t.rows:
        w.writerow([plain(c) for c in r])
    return buf.getvalue().encode("utf-8")


def write(ms_dir: Path, root: Path = ROOT) -> list[str]:
    ex = ms_dir / "exhibits"
    ex.mkdir(parents=True, exist_ok=True)
    tables = build(root)
    (ex / "tables.md").write_text(render_md(tables), encoding="utf-8", newline="\n")
    for t in tables:
        (ex / t.csv_name).write_bytes(csv_bytes(t))
    return [f"{t.label}: {len(t.rows)} rows -> {t.csv_name}" for t in tables]


