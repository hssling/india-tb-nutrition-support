def where(source: str) -> str:
    s = source.split(" (")[0]
    return {"npy_panel.csv": "NPY table", "chain": "Payment chain", "sector_panel.csv": "Notifications by sector",
            "priority": "Tiers", "2023 national totals": "2023 national totals", "funnel": "Funnel",
            "H1": "H1", "H2": "H2"}.get(s, s)


def reason(text: str) -> str:
    if "all_members_missing" in text:
        return "printed as a dash"
    m = re.search(r"member_missing:([^;]+)", text)
    if m and text.startswith("merged unit"):
        return f"merged unit: the {m.group(1)} cell is printed NA and adds nothing"
    for k, v in CODES.items():
        text = text.replace(k, v)
    return text.replace("NA: ", "").replace(" NA ", " is NA ").replace("_", " ")


def measure(m: str) -> str:
    return {"bank_available": "bank details available", "bank_validated": "bank details validated",
            "tiers (U and U wt_u)": "tiers (U and U × wt_u)"}.get(m, m)


def tables2(root: Path) -> Table:
    rows = [[where(r["source"]), r["unit"], r["year"], measure(r["measure"]), reason(r["reason"])]
            for r in read_csv(root, "outputs/na_cells.csv")]
    notes = ["Nothing is imputed and nothing is carried forward from an earlier year. A unit with an NA measure is left out "
             "only of the quantities that use it; 2023 national totals are for the units with data."]
    return Table("S:na", "NA cells and exclusions", ["Where", "Unit", "Year", "Measure", "Reason"], rows, notes)


