    nbar = by[(units[0], "sex_weighted")]["n_bar"]
    notes = [f"w_u and m_u: NFHS-5 items 86 and 87 (BMI below 18.5 kg/m², ages 15–49, Total column); merged units are "
             f"weighted by their members' 2022 notified counts. n_u = f_u w_u + (1 − f_u) m_u, with transgender patients "
             f"weighted with men. The notification-weighted mean of n_u is {pct(nbar)}, and wt_u = n_u divided by it. The "
             f"weight is relative: it says where an unpaid person is more likely to be underweight, and it is not a count "
             f"of undernourished TB patients."]
    return Table("S:need", "The relative need weight by unit, with the sensitivity weightings",
                 ["Unit", "Women, BMI below 18.5 (w_u)", "Men (m_u)", "Female share of notified, 2022 (f_u)",
                  "Notified, 2022", "Need share n_u", "wt_u, sex-weighted", "wt_u, women only", "wt_u, men only",
                  "wt_u, simple average"], rows, notes)


